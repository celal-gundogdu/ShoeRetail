-- 20) supplier_payments
--     Üreticiye YAPTIĞIMIZ ödemeler. payments'ın üretici aynası.
--
--     ASİMETRİ (spec §8.3, bilinçli): üretici tarafında taksit planı, taksit
--     ve dağıtım tablosu YOKTUR. Vadeyi üretici koyar
--     (purchase_orders.payment_due_date), biz ne ödediğimizi kaydederiz.
--     Kontrolü bizde olmayan bir süreci detaylı modellemek anlamsızdır.
--     Gereksiz simetri kurmak da bir over-engineering biçimidir.
--
--     payments'tan TEK YAPISAL FARK: purchase_order_id kolonu var.
--     Ödeme yaparken hangi faturayı kapattığımızı biliriz — ama toplu ödeme
--     ve avans senaryoları için nullable bırakıldı.
--
--     🔴 GİZLİLİK: bu tablo üreticiye ASLA açılmaz. Ödeme tarihlerimizi
--     görmesi nakit akışımızı ve pazarlık gücümüzü ele verir. Faz 18'de
--     Manufacturer rolüne bu tablo için hiçbir endpoint yok → 403.
--
--     Ters kayıt deseni payments ile BİREBİR AYNI (kasıtlı tutarlılık).
-- ─────────────────────────────
CREATE TABLE supplier_payments (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id           bigint        NOT NULL,

    -- Hangi faturayı kapatıyor? Toplu ödeme/avansta NULL.
    purchase_order_id     bigint        NULL,

    amount                numeric(18,2) NOT NULL,
    payment_method        varchar(20)   NOT NULL,
    payment_date          date          NOT NULL,   -- paranın FİİLEN çıktığı gün

    reference_no          varchar(100)  NULL,       -- dekont / çek no
    notes                 text          NULL,

    -- Ters kayıt (spec §8.4) — payments ile aynı desen
    status                varchar(20)   NOT NULL DEFAULT 'Active',
    reversed_at           timestamptz   NULL,
    reversed_by_user_id   bigint        NULL,
    reversal_reason       text          NULL,

    created_by_user_id    bigint        NOT NULL,
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_supplier_payments_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_payments_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_payments_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_payments_reversed_by
        FOREIGN KEY (reversed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT chk_supplier_payments_amount_positive
        CHECK (amount > 0),

    CONSTRAINT chk_supplier_payments_method
        CHECK (payment_method IN ('Cash', 'BankTransfer', 'CreditCard', 'Cheque', 'PromissoryNote')),

    CONSTRAINT chk_supplier_payments_status
        CHECK (status IN ('Active', 'Reversed')),

    CONSTRAINT chk_supplier_payments_reversal_consistency
        CHECK (
            (status = 'Active'
                AND reversed_at IS NULL
                AND reversed_by_user_id IS NULL
                AND reversal_reason IS NULL)
            OR
            (status = 'Reversed'
                AND reversed_at IS NOT NULL
                AND reversed_by_user_id IS NOT NULL
                -- IS NOT NULL sart: btrim(NULL) <> '' sonucu NULL'dir ve CHECK,
                -- NULL sonucu GECERLI sayar -> guard olmadan gerekcesiz iptal gecerdi.
                AND reversal_reason IS NOT NULL
                AND btrim(reversal_reason) <> '')
        )
);

