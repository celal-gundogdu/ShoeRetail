-- 17) payments
--     Perakendeciden FİİLEN ALINAN para. installments'ın karşıtı:
--     o "alınması gereken", bu "alınmış olan".
--
--     MÜŞTERİ SEVİYESİNDE yaşar, sipariş seviyesinde DEĞİL.
--     Müşteri "25.000 veriyorum" der, hangi taksitlere gideceğini söylemez —
--     dağıtımı sistem yapar (payment_allocations, Tablo 18).
--
--     TERS KAYIT: satır SİLİNMEZ, status = 'Reversed' işaretlenir.
--     Negatif tutarlı satır YOK — "eksi 50.000 tahsil ettik" diye bir olay
--     olmaz. Cari hesap düzeltmesi account_transactions'ta (Tablo 19) yapılır.
-- ─────────────────────────────
CREATE TABLE payments (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id           bigint        NOT NULL,

    amount                numeric(18,2) NOT NULL,
    payment_method        varchar(20)   NOT NULL,
    payment_date          date          NOT NULL,   -- paranın FİİLEN geldiği gün

    reference_no          varchar(100)  NULL,       -- dekont / çek no / makbuz no
    notes                 text          NULL,

    -- Ters kayıt (spec §8.4)
    status                varchar(20)   NOT NULL DEFAULT 'Active',
    reversed_at           timestamptz   NULL,
    reversed_by_user_id   bigint        NULL,
    reversal_reason       text          NULL,

    created_by_user_id    bigint        NOT NULL,
    created_at            timestamptz   NOT NULL DEFAULT now(),   -- SİSTEME giriş anı
    updated_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_payments_customer
        FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_reversed_by
        FOREIGN KEY (reversed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    -- Negatif ödeme YASAK: iptalin tek yolu status='Reversed' olsun diye.
    -- İki farklı iptal yöntemi yan yana yaşarsa raporlar hangisini sayacağını bilemez.
    CONSTRAINT chk_payments_amount_positive
        CHECK (amount > 0),

    CONSTRAINT chk_payments_method
        CHECK (payment_method IN ('Cash', 'BankTransfer', 'CreditCard', 'Cheque', 'PromissoryNote')),

    CONSTRAINT chk_payments_status
        CHECK (status IN ('Active', 'Reversed')),

    -- İptal edilmiş kayıt, kim/ne zaman/neden bilgisi OLMADAN var olamaz.
    -- Aktif kayıtta bu üç alan da boş olmalı (yarım iptal diye bir şey yok).
    CONSTRAINT chk_payments_reversal_consistency
        CHECK (
            (status = 'Active'
                AND reversed_at IS NULL
                AND reversed_by_user_id IS NULL
                AND reversal_reason IS NULL)
            OR
            (status = 'Reversed'
                AND reversed_at IS NOT NULL
                AND reversed_by_user_id IS NOT NULL
                -- IS NOT NULL sart: btrim(NULL) <> '' sonucu NULL'dir ve CHECK,
                -- NULL sonucu GECERLI sayar -> guard olmadan gerekcesiz iptal gecerdi.
                AND reversal_reason IS NOT NULL
                AND btrim(reversal_reason) <> '')
        )
);

-- Spec'in istediği index: müşteri cari ekstresi, tarih aralığı raporu.
CREATE INDEX ix_payments_customer_date
    ON payments (customer_id, payment_date);

-- "Bugün ne kadar tahsilat yapıldı?" — müşteri ayrımı olmadan.
CREATE INDEX ix_payments_payment_date
    ON payments (payment_date);

CREATE INDEX ix_payments_created_by
    ON payments (created_by_user_id);

-- NOT: reference_no bilinçli olarak UNIQUE DEĞİLDİR — aynı dekont numarası iki
