--     Satın alma siparişinin zaman çizelgesi. order_history'den farkı:
--     kayıtları HEM BİZ HEM ÜRETİCİ oluşturur (changed_by_user_id ikisinden
--     biri olabilir).
--     APPEND-ONLY: güncellenmez, silinmez.
--
--     GİZLİLİK 1: Üretici yalnızca changed_at >= po.sent_at olan satırları görür
--                 (taslak aşamasındaki adet değişiklikleri gizli kalır).
--     GİZLİLİK 2: Üretici DTO'sunda bizim kullanıcı adlarımız 'Alıcı' olarak
--                 maskelenir; kendi kullanıcıları gerçek adıyla görünür.
--     GİZLİLİK 3: internal_notes değişiklikleri buraya YAZILMAZ — "iç not değişti"
--                 satırı bile bilgi sızıntısıdır. O kayıtlar audit_logs'a gider.
-- ─────────────────────────────
CREATE TABLE purchase_order_history (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
