-- ─────────────────────────────
-- 21) supplier_transactions
--     Üretici cari defteri. account_transactions'ın aynası.
--     suppliers.balance diye bir kolon YOKTUR:  bakiye = SUM(amount)
--
--     🔴 İŞARET KONVANSİYONU — account_transactions'ın TERS PERSPEKTİFİ:
--       amount > 0  →  BİZİM BORCUMUZ ARTAR   (mal kabul edildi)
--       amount < 0  →  BİZİM BORCUMUZ AZALIR  (ödeme yaptık)
--       Bakiye > 0  →  üreticiye borçluyuz (normal durum)
--       Bakiye < 0  →  üretici bize borçlu (avans / fazla ödeme)
--       Bakiye = 0  →  hesap kapalı
--
--     Her iki defterde de "bakiye pozitif = borç var" okunur; yalnızca
--     borçlunun kim olduğu tabloya göre değişir. Bu kasıtlıdır — ekranda
--     eksi rakamı "borç" diye okumak zorunda kalmamak için.
--
--     🔑 Purchase, sipariş VERİLDİĞİNDE değil MAL KABUL EDİLDİĞİNDE doğar.
--     (Sale'in sevkiyatta doğmasının simetriği: mal gelmeden borç doğmaz.)
--     Kısmi mal kabul → her parti kendi Purchase satırını yazar; böylece
--     gelmemiş malın parası borç olarak görünmez.
--
--     🔴 GİZLİLİK: üretici bu defteri göremez. Bakiyesini görebilir (tek bir
--     SUM olarak), defterin kendisini değil. Her sorgu token'daki supplier_id
--     ile filtrelenir — invariant #2.
--
--     SAF APPEND-ONLY: UPDATE yok, DELETE yok, updated_at yok, status yok.
--     Ters kayıt = ters yönlü YENİ SATIR.
-- ─────────────────────────────
CREATE TABLE supplier_transactions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id           bigint        NOT NULL,

    transaction_type      varchar(20)   NOT NULL,
    amount                numeric(18,2) NOT NULL,   -- işaretli

    -- Kaynak belge (tipine göre biri dolu olur)
    purchase_order_id     bigint        NULL,
    supplier_payment_id   bigint        NULL,

    description           text          NULL,

    created_by_user_id    bigint        NOT NULL,
    created_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_supplier_transactions_supplier
        FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_transactions_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_transactions_payment
        FOREIGN KEY (supplier_payment_id) REFERENCES supplier_payments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_supplier_transactions_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT chk_supplier_transactions_amount_nonzero
        CHECK (amount <> 0),

    CONSTRAINT chk_supplier_transactions_type_signature
        CHECK (
            -- Mal kabul: borcumuz artar, satın alma siparişine bağlı ZORUNLU
            (transaction_type = 'Purchase'
                AND amount > 0
                AND purchase_order_id IS NOT NULL AND supplier_payment_id IS NULL)
            OR
            -- Ödeme: borcumuz azalır, ödeme kaydına bağlı ZORUNLU.
            -- purchase_order_id BURADA da dolu olabilir: faturaya bağlı ödemede
            -- defterde de görünmesi ekstreyi okunur kılar. (account_transactions'ta
            -- Payment için order_id IS NULL zorlanıyordu — aynalamanın bilinçli
            -- olarak kırıldığı tek nokta; iş akışı gerçekten farklı.)
            (transaction_type = 'Payment'
                AND amount < 0
                AND supplier_payment_id IS NOT NULL)
            OR
            -- Ters kayıt: işaret serbest, bir kaynağa bağlı olmak zorunda
            (transaction_type = 'Reversal'
                AND (purchase_order_id IS NOT NULL OR supplier_payment_id IS NOT NULL))
            OR
            -- Manuel düzeltme: kaynak belgesi olmayabilir, açıklama ZORUNLU
            -- (siparişsiz mal alımı buraya düşer).
            -- IS NOT NULL şart: btrim(NULL) <> '' sonucu NULL'dır ve CHECK,
            -- NULL sonucu GEÇERLİ sayar → guard olmadan gerekçesiz satır geçerdi.
            (transaction_type = 'Adjustment'
                AND description IS NOT NULL
                AND btrim(description) <> '')
        )
);

-- Üretici cari ekstresi (spec'in istediği index)
CREATE INDEX ix_supplier_transactions_supplier_created
    ON supplier_transactions (supplier_id, created_at);

CREATE INDEX ix_supplier_transactions_purchase_order_id
    ON supplier_transactions (purchase_order_id);
CREATE INDEX ix_supplier_transactions_payment_id
    ON supplier_transactions (supplier_payment_id);
CREATE INDEX ix_supplier_transactions_created_by
    ON supplier_transactions (created_by_user_id);


