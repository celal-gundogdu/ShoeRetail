-- ─────────────────────────────
-- 18) payment_allocations
--     payments ↔ installments köprüsü. Taşıyan (M:N + amount) ara tablo:
--     sadece "bağlı" değil, "NE KADARIYLA bağlı" bilgisini tutar.
--
--     Bir ödeme birden çok taksidi kapatabilir; bir taksit birden çok ödemeyle
--     kısmen kapanabilir. Dağıtımı sistem yapar: en eski vadesi geçmiş
--     taksitten başlayarak (spec §8.2).
--
--     status/is_reversed KOLONU YOKTUR — dağıtım kendi başına iptal edilmez,
--     bağlı olduğu ödeme iptal edilir. Sorgular
--     JOIN payments p ... AND p.status = 'Active' ile filtreler.
--     İkinci bir durum alanı iki doğruluk kaynağı yaratırdı.
--
--     SİLİNEBİLİR: para değil, paranın ATFI. "Dağıtımı Değiştir" eski
--     satırları silip yenilerini yazar; payments dokunulmaz kalır.
-- ─────────────────────────────
CREATE TABLE payment_allocations (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    payment_id            bigint        NOT NULL,
    installment_id        bigint        NOT NULL,

    amount                numeric(18,2) NOT NULL,

    created_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_payment_allocations_payment
        FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE RESTRICT,

    -- Bu RESTRICT, Tablo 16'da söz verilen korumadır:
    -- dağıtımı olan taksit SİLİNEMEZ. Uygulama kodu gerekmez.
    CONSTRAINT fk_payment_allocations_installment
        FOREIGN KEY (installment_id) REFERENCES installments(id) ON DELETE RESTRICT,

    CONSTRAINT chk_payment_allocations_amount_positive
        CHECK (amount > 0)
);

-- "Bu ödeme nereye dağıtıldı?" — ödeme detay ekranı
CREATE INDEX ix_payment_allocations_payment_id
    ON payment_allocations (payment_id);

-- "Bu taksit ne kadar ödendi?" — tahsilat panosunun sıcak sorgusu
CREATE INDEX ix_payment_allocations_installment_id
    ON payment_allocations (installment_id);

-- NOT: UNIQUE (payment_id, installment_id) bilinçli olarak YOKTUR.
-- UNIQUE, satır birleştirmeyi (UPDATE) zorunlu kılar; bu tablo bir defterdir
-- ve satırları güncellenmez. Gerçek koruma iki toplam kuralıdır ve onlar
