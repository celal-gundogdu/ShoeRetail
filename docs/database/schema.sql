    changed_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_po_history_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_po_history_changed_by
        FOREIGN KEY (changed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT chk_po_history_event_type
        CHECK (event_type IN (
            'Created',
            'StatusChanged',
            'ItemAdded',
            'ItemChanged',
            'ItemRemoved',
            'GoodsReceived',
            'NoteChanged',
            'ExpectedDeliveryDateChanged',
            'SupplierReferenceChanged'
        ))
);

CREATE INDEX ix_po_history_order_id_changed_at
    ON purchase_order_history (purchase_order_id, changed_at);

CREATE INDEX ix_po_history_changed_by_user_id
    ON purchase_order_history (changed_by_user_id);


-- ─────────────────────────────
-- 14) inventory_movements
--     Stok hareket defteri. inventory "şu an 17 var" der; bu tablo "NEDEN 17?"
--     sorusunu cevaplar. account_transactions'ın stok tarafındaki ikizi.
--     APPEND-ONLY: yanlış hareket düzeltme hareketiyle telafi edilir, satır
--     güncellenmez/silinmez.
--
--     NOT: v1'de bu tablo orders'tan ÖNCE geliyordu ve FK sırası sorunu vardı.
--     Yeni sıralamada orders (8) ve purchase_orders (11) hazır — sorun yapısal
--     olarak ortadan kalktı.
-- ─────────────────────────────
CREATE TABLE inventory_movements (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_variant_id    bigint        NOT NULL,

    movement_type         varchar(30)   NOT NULL,
    on_hand_delta         integer       NOT NULL DEFAULT 0,
    reserved_delta        integer       NOT NULL DEFAULT 0,

    -- Hangi belgeye bağlı (tipine göre biri dolu olur)
    order_id              bigint        NULL,
    purchase_order_id     bigint        NULL,

    reason                text          NULL,

    created_by_user_id    bigint        NOT NULL,
    created_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_inventory_movements_variant
        FOREIGN KEY (product_variant_id) REFERENCES product_variants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_movements_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_movements_purchase_order
        FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_movements_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    -- Her tipin işaret imzası. Geçerli tip listesini de zorlar:
    -- listede olmayan bir tip hiçbir dala uymaz ve reddedilir.
    -- 'Sale' için reserved_delta <= 0 (bilinçli olarak gevşek): sıkı kısıt,
    -- rezervasyonu düşmüş bir siparişin sevkiyat transaction'ını patlatırdı.
    CONSTRAINT chk_inventory_movements_type_signature
        CHECK (
            (movement_type = 'InitialStock'        AND on_hand_delta >  0 AND reserved_delta =  0) OR
            (movement_type = 'Purchase'            AND on_hand_delta >  0 AND reserved_delta =  0) OR
            (movement_type = 'Return'              AND on_hand_delta >  0 AND reserved_delta =  0) OR
            (movement_type = 'ManualIncrease'      AND on_hand_delta >  0 AND reserved_delta =  0) OR
            (movement_type = 'OrderReservation'    AND on_hand_delta =  0 AND reserved_delta >  0) OR
            (movement_type = 'ReservationReleased' AND on_hand_delta =  0 AND reserved_delta <  0) OR
            (movement_type = 'Sale'                AND on_hand_delta <  0 AND reserved_delta <= 0) OR
            (movement_type = 'ManualDecrease'      AND on_hand_delta <  0 AND reserved_delta =  0) OR
            (movement_type = 'Damaged'             AND on_hand_delta <  0 AND reserved_delta =  0)
        ),

    -- Elle stok değişikliği gerekçesiz olamaz (denetlenebilirlik)
    CONSTRAINT chk_inventory_movements_manual_reason
        CHECK (
            movement_type NOT IN ('ManualIncrease','ManualDecrease','Damaged')
            OR (reason IS NOT NULL AND btrim(reason) <> '')
        ),

    -- Sipariş kaynaklı hareketler siparişe bağlı olmak zorunda.
    -- purchase_order_id zorunlu DEĞİL: siparişsiz mal alımı meşru bir senaryo.
    CONSTRAINT chk_inventory_movements_order_link
        CHECK (
            movement_type NOT IN ('Sale','OrderReservation','ReservationReleased')
            OR order_id IS NOT NULL
        )
);

CREATE INDEX ix_inventory_movements_variant_created
    ON inventory_movements (product_variant_id, created_at);
CREATE INDEX ix_inventory_movements_order_id
    ON inventory_movements (order_id);
CREATE INDEX ix_inventory_movements_purchase_order_id
    ON inventory_movements (purchase_order_id);
CREATE INDEX ix_inventory_movements_type_created
    ON inventory_movements (movement_type, created_at);
CREATE INDEX ix_inventory_movements_created_by
    ON inventory_movements (created_by_user_id);
