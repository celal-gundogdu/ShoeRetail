-- ─────────────────────────────
-- 19) account_transactions
--     Perakendeci cari defteri. Müşteri bakiyesinin TEK doğruluk kaynağı.
--     customers.balance diye bir kolon YOKTUR ve olmayacaktır:
--       bakiye = SUM(amount)   (spec §8.5)
--
--     İŞARET KONVANSİYONU (kilitli):
--       amount > 0  →  müşterinin borcu ARTAR   (sipariş sevk edildi)
--       amount < 0  →  müşterinin borcu AZALIR  (tahsilat yapıldı)
--       Bakiye > 0  →  müşteri bize borçlu (normal durum)
--       Bakiye < 0  →  biz müşteriye borçluyuz (avans / fazla tahsilat)
--       Bakiye = 0  →  hesap kapalı
--
--     SAF APPEND-ONLY: UPDATE yok, DELETE yok, updated_at yok, status yok.
--     Ters kayıt = ters yönlü YENİ SATIR. (payments'taki 'Reversed'
--     işaretlemesinden farklı: orası fiziksel OLAY, burası MUHASEBE ETKİSİ.
--     "Eksi tahsilat" diye bir olay olmaz ama eksi defter satırı anlamlıdır.)
-- ─────────────────────────────
CREATE TABLE account_transactions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id           bigint        NOT NULL,

    transaction_type      varchar(20)   NOT NULL,
    amount                numeric(18,2) NOT NULL,   -- işaretli

    -- Kaynak belge (tipine göre biri dolu olur)
    order_id              bigint        NULL,
    payment_id            bigint        NULL,

    description           text          NULL,

    created_by_user_id    bigint        NOT NULL,
    created_at            timestamptz   NOT NULL DEFAULT now(),

    CONSTRAINT fk_account_transactions_customer
        FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_account_transactions_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_account_transactions_payment
        FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_account_transactions_created_by
        FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,

    -- Sıfır tutarlı defter satırı gürültüdür.
    CONSTRAINT chk_account_transactions_amount_nonzero
        CHECK (amount <> 0),

    -- Tip ↔ işaret ↔ kaynak belge imzası.
    -- inventory_movements.chk_..._type_signature'ın finans karşılığı:
    -- geçerli tip listesini de zorlar (listede olmayan tip hiçbir dala uymaz).
    CONSTRAINT chk_account_transactions_type_signature
        CHECK (
            -- Sipariş sevkiyatı: borç artar, siparişe bağlı olmak ZORUNDA
            (transaction_type = 'Sale'
                AND amount > 0
                AND order_id IS NOT NULL AND payment_id IS NULL)
            OR
            -- Tahsilat: borç azalır, ödemeye bağlı olmak ZORUNDA
            (transaction_type = 'Payment'
                AND amount < 0
                AND payment_id IS NOT NULL AND order_id IS NULL)
            OR
            -- Ters kayıt: işaret serbest (neyi ters çevirdiğine bağlı),
            -- ama bir kaynağa bağlı olmak zorunda
            (transaction_type = 'Reversal'
                AND (order_id IS NOT NULL OR payment_id IS NOT NULL))
            OR
            -- Manuel düzeltme: kaynak belgesi olmayabilir, ama açıklama ZORUNLU.
            -- IS NOT NULL şart: btrim(NULL) <> '' sonucu NULL'dır ve CHECK,
            -- NULL sonucu GEÇERLİ sayar → guard olmadan gerekçesiz satır geçerdi.
            (transaction_type = 'Adjustment'
                AND description IS NOT NULL
                AND btrim(description) <> '')
        )
);

-- Cari ekstre sorgusunun index'i (spec'in istediği):
-- "Bu müşterinin hareketleri, tarih sırasıyla"
CREATE INDEX ix_account_transactions_customer_created
    ON account_transactions (customer_id, created_at);

CREATE INDEX ix_account_transactions_order_id
    ON account_transactions (order_id);
CREATE INDEX ix_account_transactions_payment_id
    ON account_transactions (payment_id);
CREATE INDEX ix_account_transactions_created_by
    ON account_transactions (created_by_user_id);

